def run_report(cfg: dict) -> None:
    """Render one self-contained HTML QC report with every image base64-inlined."""
    artifacts_dir = resolve_path(cfg, cfg["paths"]["artifacts"])
    report_cfg = cfg["report"]
    n_examples = report_cfg["n_examples_per_panel"]

    context: dict = {}

    # --- dataset overview + leakage-audit findings (reused from notebooks/) ---
    eda = _import_notebook_module("eda")
    findings = _import_notebook_module("findings_charts")
    context["eda_sections"] = eda.build_sections()
    context["findings_sections"] = findings.build_sections()

    # --- results table ---
    summary = _aggregate_results(cfg)
    context["headline"] = _headline_text(summary)
    if not summary.empty:
        display = summary.copy()
        for col, mean_col, std_col in [
            ("AUROC", "auroc_mean", "auroc_std"),
            ("AUPRC", "auprc_mean", "auprc_std"),
            ("Sens@95%Spec", "sens_mean", "sens_std"),
        ]:
            display[col] = display.apply(
                lambda r, m=mean_col, s=std_col: f"{r[m]:.3f} ± {r[s]:.3f}"
                if pd.notna(r[s])
                else f"{r[m]:.3f}",
                axis=1,
            )
        display = display.rename(
            columns={"arm": "Arm", "n_seeds": "N seeds", "n_train": "N train"}
        )[["Arm", "N seeds", "N train", "AUROC", "AUPRC", "Sens@95%Spec"]]
        context["results_html"] = display.to_html(index=False, border=0)
    else:
        context["results_html"] = ""

    # --- quality panels ---
    quality_path = artifacts_dir / "quality.parquet"
    reject_below = cfg["quality"]["reject_below_score"]
    if quality_path.exists():
        quality_df = pd.read_parquet(quality_path)
        rejects = quality_df[quality_df["score"] < reject_below].sort_values("score")

        context["quality_hist"] = _quality_score_histogram(quality_df, reject_below)
        context["n_total"] = len(quality_df)
        context["n_rejected"] = len(rejects)
        reject_pct = len(rejects) / len(quality_df) * 100 if len(quality_df) else 0
        context["reject_pct"] = round(reject_pct, 1)
        context["reject_below"] = reject_below

        rejects_csv_path = artifacts_dir / "rejects.csv"
        reasons_by_path = {}
        if rejects_csv_path.exists():
            reasons_df = pd.read_csv(rejects_csv_path)
            reasons_by_path = dict(
                zip(reasons_df["image_path"], reasons_df["reason"], strict=False)
            )

        examples = []
        for _, row in rejects.head(n_examples).iterrows():
            examples.append(
                {
                    "thumb": _image_to_base64_thumbnail(row["image_path"]),
                    "score": row["score"],
                    "reason": reasons_by_path.get(row["image_path"], "below score threshold"),
                }
            )
        context["reject_examples"] = examples
    else:
        context["quality_hist"] = None
        context["n_total"] = 0
        context["n_rejected"] = 0
        context["reject_pct"] = 0
        context["reject_below"] = reject_below
        context["reject_examples"] = []

    # --- duplicate clusters ---
    dup_path = artifacts_dir / "duplicates.parquet"
    duplicate_clusters = []
    if dup_path.exists():
        dup_df = pd.read_parquet(dup_path)
        dup_only = dup_df[dup_df["is_duplicate"]]
        cluster_ids = sorted(dup_only["cluster_id"].unique())[:n_examples]
        for cid in cluster_ids:
            paths = dup_only.loc[dup_only["cluster_id"] == cid, "image_path"]
            duplicate_clusters.append([{"thumb": _image_to_base64_thumbnail(p)} for p in paths])
    context["duplicate_clusters"] = duplicate_clusters

    # --- class balance before/after curation ---
    manifest_path = artifacts_dir / "manifest.parquet"
    if manifest_path.exists():
        manifest = pd.read_parquet(manifest_path)
        balances = {"raw": manifest["label"].value_counts(normalize=True)}
        if quality_path.exists():
            quality_df = pd.read_parquet(quality_path)
            rejected_paths = set(quality_df.loc[quality_df["score"] < reject_below, "image_path"])
            curated = manifest[~manifest["image_path"].isin(rejected_paths)]
            balances["quality-curated"] = curated["label"].value_counts(normalize=True)
            if dup_path.exists():
                dup_df = pd.read_parquet(dup_path)
                quality_by_path = quality_df.set_index("image_path")["score"]
                drop: set[str] = set()
                curated_paths = set(curated["image_path"])
                for _cid, group in dup_df[dup_df["is_duplicate"]].groupby("cluster_id"):
                    survivors = [p for p in group["image_path"] if p in curated_paths]
                    if len(survivors) < 2:
                        continue
                    keep = max(survivors, key=lambda p: quality_by_path.get(p, 0.0))
                    drop.update(p for p in survivors if p != keep)
                deduped = curated[~curated["image_path"].isin(drop)]
                balances["quality+dedupe"] = deduped["label"].value_counts(normalize=True)
        context["class_balance_chart"] = _class_balance_chart(balances)
    else:
        context["class_balance_chart"] = None

    html = REPORT_TEMPLATE.render(**context)

    output_path = Path(resolve_path(cfg, report_cfg["output_html"]))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(html, encoding="utf-8")
    logger.info("Wrote %s (%d bytes)", output_path, len(html))
