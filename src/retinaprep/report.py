def _import_notebook_module(name: str) -> ModuleType:
    """Import a notebooks/<name>.py script as a module.

    notebooks/ scripts are standalone (not part of the installed package)
    but export a build_sections() reusable by this report -- loading by
    file path avoids depending on notebooks/ being importable via sys.path.
    """
    path = REPO_ROOT / "notebooks" / f"{name}.py"
    spec = importlib.util.spec_from_file_location(f"retinaprep_notebooks_{name}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fig_to_base64(fig) -> str:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight")
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def _image_to_base64_thumbnail(path: str, size: int = 150) -> str:
    try:
        with Image.open(path) as im:
            thumb = im.convert("RGB")
            thumb.thumbnail((size, size))
            buf = io.BytesIO()
            thumb.save(buf, format="JPEG", quality=80)
            return base64.b64encode(buf.getvalue()).decode("ascii")
    except OSError:
        return ""


def _quality_score_histogram(quality_df: pd.DataFrame, reject_below: float) -> str:
    fig, ax = plt.subplots(figsize=(7, 3.5))
    ax.hist(quality_df["score"], bins=40, color="#4C72B0", edgecolor="white")
    ax.axvline(
        reject_below, color="#C44E52", linestyle="--", label=f"reject threshold ({reject_below})"
    )
    ax.set_xlabel("Gradability score")
    ax.set_ylabel("Count")
    ax.set_title(f"Quality score distribution (n={len(quality_df)})")
    ax.legend()
    fig.tight_layout()
    return _fig_to_base64(fig)


def _class_balance_chart(balances: dict[str, pd.Series]) -> str:
    fig, ax = plt.subplots(figsize=(6, 3.5))
    labels = list(balances.keys())
    normal_fracs = [balances[k].get(0, 0.0) for k in labels]
    abnormal_fracs = [balances[k].get(1, 0.0) for k in labels]
    x = range(len(labels))
    ax.bar(x, normal_fracs, label="normal (0)", color="#55A868")
    ax.bar(x, abnormal_fracs, bottom=normal_fracs, label="abnormal (1)", color="#C44E52")
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels)
    ax.set_ylabel("Fraction")
    ax.set_title("Class balance before/after curation")
    ax.legend(loc="lower right")
    fig.tight_layout()
    return _fig_to_base64(fig)


def _aggregate_results(cfg: dict) -> pd.DataFrame:
    artifacts_dir = resolve_path(cfg, cfg["paths"]["artifacts"])
    runs_dir = artifacts_dir / "runs"
    rows = []
    if runs_dir.is_dir():
        for run_dir in sorted(runs_dir.iterdir()):
            metrics_path = run_dir / "metrics.json"
            if metrics_path.exists():
                with open(metrics_path) as fh:
                    r = json.load(fh)
                tm = r["test_metrics"]
                rows.append(
                    {
                        "arm": r.get("arm") or "-",
                        "seed": r["seed"],
                        "n_train": r["n_train"],
                        "auroc": tm["auroc"],
                        "auprc": tm["auprc"],
                        "sens_95_spec": tm["sensitivity_at_95_specificity"],
                    }
                )
    if not rows:
        return pd.DataFrame()

    df = pd.DataFrame(rows)
    summary = df.groupby("arm").agg(
        n_seeds=("seed", "count"),
        n_train=("n_train", "first"),
        auroc_mean=("auroc", "mean"),
        auroc_std=("auroc", "std"),
        auprc_mean=("auprc", "mean"),
        auprc_std=("auprc", "std"),
        sens_mean=("sens_95_spec", "mean"),
        sens_std=("sens_95_spec", "std"),
    )
    return summary.reset_index()


def _headline_text(summary: pd.DataFrame) -> str:
    if summary.empty:
        return (
            "No experiment runs found yet under artifacts/runs/ -- "
            "run the experiment step first."
        )
    row = summary.set_index("arm")
    if "A" not in row.index or "B" not in row.index:
        return "Arms A and B are not both present in artifacts/runs/ yet."
    diff = row.loc["A", "auroc_mean"] - row.loc["B", "auroc_mean"]
    return (
        f"Training on a naive image-level split (arm A) measures "
        f"{row.loc['A', 'auroc_mean']:.3f} AUROC; the correct patient-grouped split "
        f"(arm B) measures {row.loc['B', 'auroc_mean']:.3f} -- a {diff:+.3f} AUROC gap, "
        f"same data, same model, same seeds, in the direction the leakage hypothesis "
        f"predicts. Section 2 below shows why any such gap should be modest even if "
        f"real (fellow-eye labels only agree 78% of the time, not 100%), and Section 4 "
        f"shows this particular gap does not replicate significantly at n=5 seeds in a "
        f"second run -- read both before treating either number as settled."
    )


